# A folder for a Shiny app that holds every source: the app.R fixture, a
# renv.lock (shiny 1.8.0, DT 0.33), a manifest.json (shiny 1.8.1) and a rix
# default.nix (shiny, DT and jsonlite).
local_app_with_all_sources <- function(env = parent.frame()) {
  dir <- file.path(withr::local_tempdir(.local_envir = env), "app")
  dir.create(dir)
  file.copy(test_path("fixtures", "shiny", "app-r", "app.R"), dir)
  file.copy(test_path("fixtures", "shiny", "app-r", "www"), dir, recursive = TRUE)
  pkg <- function(name, version) {
    list(
      Package = name, Version = version, Source = "Repository", Repository = "CRAN",
      License = "GPL-3", Maintainer = "Test Person <person@example.org>"
    )
  }
  write_text(
    jsonlite::toJSON(list(
      R = list(Version = "4.4.1", Repositories = list(list(Name = "CRAN", URL = "https://cloud.r-project.org"))),
      Packages = list(shiny = pkg("shiny", "1.8.0"), DT = pkg("DT", "0.33"))
    ), auto_unbox = TRUE, pretty = TRUE),
    file.path(dir, "renv.lock")
  )
  entry <- function(name, version) {
    list(Source = "CRAN", Repository = "https://cloud.r-project.org", description = list(
      Package = name, Version = version, License = "GPL-3", Repository = "CRAN",
      Maintainer = "Test Person <person@example.org>"
    ))
  }
  write_text(
    jsonlite::toJSON(list(
      version = 1, locale = "en_US", platform = "4.4.1",
      metadata = list(appmode = "shiny", primary_rmd = NULL, primary_html = NULL),
      packages = list(shiny = entry("shiny", "1.8.1")),
      files = list(app.R = list(checksum = "0"))
    ), auto_unbox = TRUE, pretty = TRUE, null = "null"),
    file.path(dir, "manifest.json")
  )
  write_text(
    c(
      "# This file was generated by the {rix} R package v0.18.6 on 2026-11-05",
      "# with following call:",
      "# >rix(r_ver = \"4.4.1\",",
      "#  > r_pkgs = c(\"shiny\", \"DT\", \"jsonlite\"),",
      "#  > project_path = \".\")",
      "let",
      " pkgs = import (fetchTarball {",
      "   url = \"https://github.com/rstats-on-nix/nixpkgs/archive/2024-10-01.tar.gz\";",
      "   sha256 = \"1nbr6m9fza4jd73wy55f9khpszxck4dxilcr8prf137syh25849f\";",
      " }) {};",
      " rpkgs = builtins.attrValues {",
      "   inherit (pkgs.rPackages)",
      "     shiny",
      "     DT",
      "     jsonlite;",
      " };",
      "in",
      "  {",
      "    inherit pkgs rpkgs;",
      "  }"
    ) |> paste(collapse = "\n") |> paste0("\n"),
    file.path(dir, "default.nix")
  )
  dir
}

# A folder with no packages in it, so that nothing depends on this machine.
empty_lib <- function(env = parent.frame()) local_fake_lib(list(), env = env)

app_sbom <- function(dir, lib) {
  sbom(dir, system = FALSE, timestamp = 0, lib = lib, library = lib, nix = FALSE)
}

nix_mode_sbom <- function() {
  sbom_nix(
    test_path("fixtures", "nix", "rix-date.nix"), nix = TRUE, system = FALSE,
    embedded = FALSE, timestamp = 0
  )
}

test_that("an app with renv.lock, manifest.json and default.nix has one root and reports every mismatch", {
  dir <- local_app_with_all_sources()
  x <- app_sbom(dir, empty_lib())
  comps <- sbom_components(x)
  expect_equal(sum(comps$is_root), 1L)
  expect_equal(comps$type[comps$is_root], "application")
  iss <- sbom_issues(x)
  expect_true("drift-version" %in% iss$code)
  expect_true("drift-extra" %in% iss$code)
  expect_match(iss$message[iss$code == "drift-extra"], "jsonlite", fixed = TRUE, all = FALSE)
  expect_false(any(grepl("default.nix", iss$message[iss$code == "drift-version"], fixed = TRUE)))
  expect_true(any(x$metadata$inputs$kind == "default.nix"))
  expect_true(all(c("renv.lock", "manifest.json", "default.nix") %in% x$metadata$inputs$kind))
  expect_null(attr(x, "records"))
})

test_that("the Shiny and Nix SBOMs validate in every format", {
  skip_on_cran()
  expect_valid_in_every_format(app_sbom(local_app_with_all_sources(), empty_lib()), "app")
  local_nix_store(test_path("fixtures", "nix", "store"))
  expect_valid_in_every_format(nix_mode_sbom(), "nix")
})

test_that("the Shiny and Nix SBOMs are byte-identical across runs and locales", {
  skip_on_cran()
  dir <- local_app_with_all_sources()
  lib <- empty_lib()
  local_nix_store(test_path("fixtures", "nix", "store"))
  builders <- list(app = function() app_sbom(dir, lib), nix = nix_mode_sbom)
  ext <- stats::setNames(sbom_formats()$extension, sbom_formats()$format)
  bytes <- function(build) {
    x <- build()
    vapply(names(ext), function(f) {
      tf <- withr::local_tempfile(fileext = ext[[f]])
      write_sbom(x, tf, format = f)
      paste(as.character(readBin(tf, "raw", file.size(tf))), collapse = "")
    }, "")
  }
  for (name in names(builders)) {
    first <- bytes(builders[[name]])
    expect_identical(bytes(builders[[name]]), first, label = paste(name, "second run"))
    local({
      local_c_ctype()
      expect_identical(bytes(builders[[name]]), first, label = paste(name, "under LC_CTYPE=C"))
    })
  }
})
