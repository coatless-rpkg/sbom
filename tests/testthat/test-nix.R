test_that("a rix file parses into its packages, git and archive packages and system packages", {
  p <- parse_rix(read_fixture("rix-date.nix"))
  expect_equal(p$nixpkgs$kind, "date"); expect_equal(p$nixpkgs$value, "2024-10-01")
  expect_equal(p$r_version, "4.4.1")
  expect_true("data.table" %in% p$packages); expect_false(any(grepl("_", p$packages)))
  expect_equal(anyDuplicated(p$packages), 0L)
  expect_equal(p$git$rev[p$git$name == "housing"], "1c860959310b80e67c41f7bbdc3e84cef00df18e")
  expect_true("dplyr" %in% p$git$inputs[[which(p$git$name == "housing")]])
  expect_equal(p$archive$version[p$archive$name == "AER"], "1.2-8")
  expect_true("glibcLocales" %in% p$system)
  expect_false("R" %in% p$system)
  expect_equal(p$tex, c("amsmath", "zmsmath"))
  expect_equal(p$other, "Python packages")
})

