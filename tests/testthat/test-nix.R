test_that("the static SBOM describes R, git and archive packages, system packages and TeX Live", {
  x <- sbom_nix(test_path("fixtures", "nix", "rix-date.nix"), nix = FALSE, system = FALSE, embedded = FALSE)
  comps <- sbom_components(x)
  rels <- sbom_dependencies(x)
  r <- comps[comps$ref == "R", ]
  expect_equal(r$version, "4.4.1"); expect_equal(r$evidence, "declared"); expect_equal(r$version_is, "exact")
  expect_false("nix/R" %in% comps$ref)

  housing <- comps[comps$name == "housing", ]
  expect_equal(housing$ecosystem, "github")
  expect_equal(housing$purl, "pkg:github/rap4all/housing@1c860959310b80e67c41f7bbdc3e84cef00df18e")
  expect_true(is.na(housing$version))
  expect_match(housing$description, "Fetched by Nix from https://github.com/rap4all/housing/ at revision 1c86", fixed = TRUE)
  expect_match(housing$description, "Nix checks it with the hash sha256-s4KGtfKQ", fixed = TRUE)
  expect_true(housing$deps_known)
  expect_true(all(c("dplyr", "purrr", "tidyr") %in% comps$name))
  expect_true(any(rels$from == housing$ref & rels$to == comps$ref[comps$name == "purrr"] & rels$field == "Imports"))

  aer <- comps[comps$name == "AER", ]
  expect_equal(aer$ecosystem, "cran"); expect_equal(aer$purl, "pkg:cran/AER@1.2-8")
  expect_match(aer$description, "cran.r-project.org/src/contrib/Archive/AER/AER_1.2-8.tar.gz", fixed = TRUE)

  dt <- comps[comps$name == "data.table", ]
  expect_false(dt$deps_known)
  # Each name once, whether declared in rpkgs, in a git package's inputs or both.
  expect_equal(anyDuplicated(comps$ref), 0L)
  expect_equal(sum(comps$name == "dplyr"), 1L)
  root <- comps$ref[comps$is_root]
  expect_true(any(rels$from == root & rels$to == dt$ref & rels$field == "Imports"))
  expect_false(any(rels$from == root & rels$to == comps$ref[comps$name == "purrr"]))

  sys <- comps[comps$ecosystem == "nix", ]
  expect_setequal(sys$ref, c("nix/glibcLocales", "nix/nix", "nix/which", "nix/texlive"))
  expect_true(all(is.na(sys$purl)))
  expect_true(all(sys$evidence == "declared"))
  expect_true(all(is.na(sys$version)))
  expect_equal(sys$type[sys$ref == "nix/nix"], "library")
  expect_equal(sys$description[sys$ref == "nix/texlive"], "TeX Live with amsmath and zmsmath.")
  expect_true(all(rels$field[rels$to %in% sys$ref] == "system_requirement"))
  expect_true(all(rels$from[rels$to %in% sys$ref] == root))
})

