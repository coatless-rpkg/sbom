# A copy of a fixture, changed by `edit`, in a new temporary folder.
edited_nix <- function(name, edit, env = parent.frame()) {
  dir <- withr::local_tempdir(.local_envir = env)
  path <- file.path(dir, "default.nix")
  write_text(edit(read_fixture(name)), path)
  path
}

