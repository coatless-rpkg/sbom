test_that("a git package's revision and an archive's URL reach SPDX", {
  path <- edited_nix("rix-date.nix", function(text) {
    gsub("https://github.com/rap4all/housing/", "https://gitlab.com/rap4all/housing", text, fixed = TRUE)
  })
  x <- sbom_nix(path, nix = FALSE, system = FALSE, embedded = FALSE)
  comps <- sbom_components(x)
  rev <- "1c860959310b80e67c41f7bbdc3e84cef00df18e"
  housing <- comps[comps$name == "housing", ]
  expect_equal(housing$ecosystem, "git")
  expect_equal(housing$download_location, paste0("git+https://gitlab.com/rap4all/housing@", rev))
  expect_equal(
    comps$download_location[comps$name == "AER"],
    "https://cran.r-project.org/src/contrib/Archive/AER/AER_1.2-8.tar.gz"
  )
  json <- withr::local_tempfile(fileext = ".spdx.json")
  write_sbom(x, json, format = "spdx-json", version = "2.3")
  doc <- jsonlite::read_json(json)
  pkg <- function(name) Filter(function(p) identical(p$name, name), doc$packages)[[1L]]
  expect_match(pkg("housing")$downloadLocation, rev, fixed = TRUE)
  expect_match(pkg("housing")$sourceInfo, paste0("Fetched by Nix from https://gitlab.com/rap4all/housing at revision ", rev), fixed = TRUE)
  expect_equal(
    pkg("AER")$downloadLocation,
    "https://cran.r-project.org/src/contrib/Archive/AER/AER_1.2-8.tar.gz"
  )
  expect_match(pkg("AER")$sourceInfo, "Nix checks it with the hash sha256-OqxX", fixed = TRUE)
  ld <- withr::local_tempfile(fileext = ".spdx3.json")
  write_sbom(x, ld, format = "spdx3-jsonld")
  elements <- jsonlite::read_json(ld)[["@graph"]]
  housing3 <- Filter(function(e) identical(e$name, "housing"), elements)[[1L]]
  expect_match(housing3$software_downloadLocation, rev, fixed = TRUE)
  expect_match(housing3$software_sourceInfo, rev, fixed = TRUE)
  expect_valid_in_every_format(x, "gitlab housing")
})

test_that("git and archive URLs lose their credentials, query and fragment", {
  path <- edited_nix("rix-date.nix", function(text) {
    text <- gsub(
      "https://github.com/rap4all/housing/", "https://user:tok@gitlab.example/x/y?private_token=abc",
      text, fixed = TRUE
    )
    sub("AER_1.2-8.tar.gz", "AER_1.2-8.tar.gz?token=abc#frag", text, fixed = TRUE)
  })
  x <- sbom_nix(path, nix = FALSE, system = FALSE, embedded = FALSE)
  comps <- sbom_components(x)
  rev <- "1c860959310b80e67c41f7bbdc3e84cef00df18e"
  housing <- comps[comps$name == "housing", ]
  expect_equal(housing$ecosystem, "git")
  expect_equal(housing$download_location, paste0("git+https://gitlab.example/x/y@", rev))
  expect_equal(housing$vcs_url, "https://gitlab.example/x/y")
  expect_match(housing$description, "^Fetched by Nix from https://gitlab.example/x/y at revision ")
  aer <- comps[comps$name == "AER", ]
  expect_equal(aer$version, "1.2-8")
  expect_equal(aer$download_location, "https://cran.r-project.org/src/contrib/Archive/AER/AER_1.2-8.tar.gz")
  for (format in c("cyclonedx-json", "spdx-json", "spdx3-jsonld")) {
    out <- withr::local_tempfile()
    write_sbom(x, out, format = format)
    text <- paste(readLines(out, warn = FALSE), collapse = "\n")
    expect_false(grepl("tok", text, fixed = TRUE), label = format)
    expect_false(grepl("frag", text, fixed = TRUE), label = format)
    expect_false(grepl("user:", text, fixed = TRUE), label = format)
  }
})

