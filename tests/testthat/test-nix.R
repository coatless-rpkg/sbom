  data.frame(
    Package = c("dplyr", "data.table", "ggplot2", "rlang", "janitor", "cli", "R6"),
    Version = c("1.1.4", "1.16.0", "3.5.1", "1.1.4", "2.2.0", "3.6.3", "2.5.1"),
    Depends = c("R (>= 3.5.0)", NA, "R (>= 3.5), stats", NA, NA, NA, "R (>= 3.0)"),
