test_that("store paths without a version are one info issue, which R packages without one join", {
  local_nix_store(store_dir())
  inner <- sys_nix_query
  source <- "sj9xaxzlyijyr97qbzmb5zip4n2kpizh-source"
  mystery <- "jmb0yhlixjnninsnbwpm9acpyj5saski-r-mystery"
  r <- "n1zxw9xqr5c68smghjkasp3i6jrpr441-R-4.4.1"
  with_paths <- function(extra) {
    function(args) {
      out <- inner(args)
      if (args[[1L]] == "--requisites") {
        out <- c(out, paste0("/nix/store/", extra))
      }
      if (args[[1L]] == "--graph") {
        edges <- paste0('"', extra, '" -> "', r, '" [color = "#000000"];')
        out <- append(out, edges, after = length(out) - 1L)
      }
      out
    }
  }
  local_mocked_bindings(sys_nix_query = with_paths(source))
  x <- nix_sbom()
  issues <- sbom_issues(x)
  hit <- issues[issues$code == "nix-store-versions-unknown", ]
  expect_equal(nrow(hit), 1L)
  expect_equal(hit$severity, "info")
  expect_equal(hit$message, "1 store path in the environment carries no version (source), so its version is unknown.")
  comps <- sbom_components(x)
  expect_true(is.na(comps$version[comps$ref == "nix/source"]))
  expect_equal(sbom_dependencies(x)$field[sbom_dependencies(x)$from == "R" & sbom_dependencies(x)$to == "nix/source"], "system_requirement")

  local_mocked_bindings(sys_nix_query = with_paths(c(source, mystery)))
  y <- nix_sbom()
  issues <- sbom_issues(y)
  expect_equal(
    issues$message[issues$code == "nix-store-versions-unknown"],
    "2 store paths in the environment carry no version (r-mystery and source), so their versions are unknown."
  )
  comps <- sbom_components(y)
  mine <- comps[comps$name == "mystery", ]
  expect_equal(mine$ecosystem, "cran")
  expect_true(is.na(mine$version))
  expect_false(any(issues$code == "version-missing" & issues$ref == mine$ref))
  # R references mystery, an R package.
  expect_equal(sbom_dependencies(y)$field[sbom_dependencies(y)$from == "R" & sbom_dependencies(y)$to == mine$ref], "Imports")
})

