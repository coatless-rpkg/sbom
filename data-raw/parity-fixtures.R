# Writes tests/testthat/fixtures/lib-dplyr-1.2.1/: one DESCRIPTION for dplyr 1.2.1 and for each of
# the 14 CRAN packages in R Observatory's sample SBOM, so the parity test can run sbom_package()
# against the same versions. Reads only the committed sample; no network. Run from the package root.
#
# Maintainer emails are not in the sample, so every one is the placeholder maintainer@example.invalid.

`%||%` <- function(x, y) if (is.null(x)) y else x

sample <- "tests/testthat/fixtures/r-observatory/dplyr-1.2.1.cdx.json"
out <- "tests/testthat/fixtures/lib-dplyr-1.2.1"

doc <- jsonlite::read_json(sample)
comps <- c(list(doc$metadata$component), doc$components)
comps <- Filter(function(c) startsWith(c$purl %||% "", "pkg:cran/"), comps)
stopifnot(length(comps) == 15L)

prop_values <- function(comp, name) {
  props <- comp$properties %||% list()
  hits <- Filter(function(p) identical(p$name, paste0("r-observatory:", name)), props)
  vapply(hits, function(p) p$value, "")
}

first_or_na <- function(x) if (length(x) > 0L) x[[1L]] else NA_character_

license_of <- function(comp) {
  written <- first_or_na(prop_values(comp, "license-as-written"))
  if (!is.na(written)) {
    return(written)
  }
  lic <- comp$licenses[[1L]]
  lic$expression %||% lic$license$name
}

vcs_of <- function(comp) {
  refs <- Filter(function(r) identical(r$type, "vcs"), comp$externalReferences %||% list())
  first_or_na(vapply(refs, function(r) r$url, ""))
}

description_lines <- function(comp) {
  maintainer <- first_or_na(prop_values(comp, "maintainer"))
  if (is.na(maintainer)) maintainer <- comp$publisher
  fields <- c(
    Package = comp$name,
    Version = comp$version,
    License = license_of(comp),
    Maintainer = paste0(maintainer, " <maintainer@example.invalid>"),
    Depends = paste(prop_values(comp, "depends"), collapse = ", "),
    Imports = paste(prop_values(comp, "imports"), collapse = ", "),
    LinkingTo = paste(prop_values(comp, "linkingto"), collapse = ", "),
    URL = vcs_of(comp),
    `Date/Publication` = paste0(first_or_na(prop_values(comp, "published")), " 00:00:00 UTC"),
    Repository = "CRAN",
    Encoding = "UTF-8"
  )
  fields <- fields[!is.na(fields) & nzchar(fields)]
  paste0(names(fields), ": ", fields)
}

unlink(out, recursive = TRUE)
dir.create(out, recursive = TRUE)
writeLines(
  c(
    "# Generated fixture library",
    "",
    "Every DESCRIPTION file under this directory is generated by",
    "`data-raw/parity-fixtures.R` from R Observatory's sample",
    "`../r-observatory/dplyr-1.2.1.cdx.json`. Do not edit them by hand.",
    "",
    "They hold only the fields that sample records. The maintainer emails are",
    "placeholders (`maintainer@example.invalid`), not real addresses."
  ),
  file.path(out, "README.md")
)
for (comp in comps) {
  dir.create(file.path(out, comp$name))
  con <- file(file.path(out, comp$name, "DESCRIPTION"), "wb")
  writeLines(enc2utf8(description_lines(comp)), con, useBytes = TRUE)
  close(con)
}
message("Wrote ", length(comps), " DESCRIPTION files under ", out, ".")
